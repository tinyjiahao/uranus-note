// Ephemeral, Cloudflare-authenticated remote preview ONLY. Never deploy this
// entrypoint or add a public route. Lifecycle is owned by remote-operations.mjs.
export default {
  async fetch(request: Request, env: { DB: D1Database; UPLOADS: R2Bucket; OPERATIONS_KEY: string }) {
    if (request.method !== "POST" || !env.OPERATIONS_KEY || request.headers.get("x-operations-key") !== env.OPERATIONS_KEY) return new Response(null, { status: 404 });
    try {
      const body = await request.json() as { action: string; statements?: { sql: string; params: unknown[] }[]; key?: string; cursor?: string };
      if (body.action === "db") {
        const statements = body.statements!;
        // All SQL is generated by the checked-in deployment tools, not users.
        if (!statements.length || statements.some(s => !s.sql.includes("uranus_") && !/^PRAGMA foreign_key_check$/i.test(s.sql) && !(s.sql === "SELECT 1 FROM sqlite_master WHERE type='table' AND name=?" && typeof s.params[0] === "string" && s.params[0].startsWith("uranus_")))) throw new Error();
        const prepared = statements.map(s => env.DB.prepare(s.sql).bind(...s.params));
        return Response.json(await env.DB.batch(prepared));
      }
      if (body.action === "list") return Response.json(await env.UPLOADS.list({ prefix: "uranus/attachments/", limit: 100, ...(body.cursor ? { cursor: body.cursor } : {}) }));
      if (!body.key?.startsWith("uranus/attachments/")) throw new Error();
      if (body.action === "head") return Response.json(await env.UPLOADS.head(body.key));
      if (body.action === "get") {
        const object = await env.UPLOADS.get(body.key);
        if (!object) return new Response(null, { status: 404 });
        return new Response(object.body, { headers: { "x-object-metadata": JSON.stringify({ httpMetadata: object.httpMetadata, customMetadata: object.customMetadata }) } });
      }
      return new Response(null, { status: 400 });
    } catch { return Response.json({ error: "CONTROLLED_OPERATION_FAILED" }, { status: 500 }); }
  },
};
