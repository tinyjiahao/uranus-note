import { test, expect } from './fixtures';
import { testEmail, testPassword } from './credentials';
test.use({ trace: 'off' });
test('label copies from popup and native selection and pastes into another note', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.goto('/login');
  await page.getByLabel('邮箱', { exact: true }).fill(testEmail());
  await page.getByLabel('密码', { exact: true }).fill(testPassword());
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.getByTitle('新建笔记 (⌘N)').click();
  const body = page.locator('.prose-editor');
  await body.click();
  await page.getByRole("button", { name: "更多格式与插入", exact: true }).click(); await page.getByRole('button', { name: '插入标签', exact: true }).click();
  await page.getByLabel('标签文字', { exact: true }).fill('复制标签');
  await page.getByRole('button', { name: '绿色', exact: true }).click();
  await page.getByRole('button', { name: '确认标签', exact: true }).click();
  await body.locator('.label-chip').click();
  const popup = page.getByRole('dialog', { name: '编辑标签' });
  await popup.getByLabel('标签文字', { exact: true }).fill('未确认文字');
  await popup.getByRole('button', { name: '蓝色', exact: true }).click();
  await expect(body.locator('.label-chip')).toHaveAttribute('data-color', 'blue');
  await popup.getByRole('button', { name: '青色', exact: true }).click();
  await expect(body.locator('.label-chip')).toHaveAttribute('data-color', 'cyan');
  await expect(body.locator('.label-chip')).toHaveText('复制标签');
  const copied = await popup.evaluate(el => {
    const data = new DataTransfer(); el.dispatchEvent(new ClipboardEvent('copy', { bubbles: true, cancelable: true, clipboardData: data }));
    return { html: data.getData('text/html'), text: data.getData('text/plain') };
  });
  expect(copied.html).toContain('data-color="cyan"');
  expect(copied.text).toBe('复制标签');
  await page.keyboard.press('Escape');
  await expect(body.locator('.label-chip')).toHaveClass(/ProseMirror-selectednode/);
  await page.keyboard.press('ControlOrMeta+c');
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('复制标签');
  await page.getByTitle('新建笔记 (⌘N)').click();
  await expect(body.locator('.label-chip')).toHaveCount(0);
  await body.click();
  await page.keyboard.press('ControlOrMeta+v');
  await expect(body.locator('.label-chip')).toHaveText('复制标签');
  await expect(body.locator('.label-chip')).toHaveAttribute('data-color', 'cyan');
  await body.locator('.label-chip').click();
  await popup.getByRole('button', { name: '紫色', exact: true }).click();
  await popup.getByLabel('标签文字', { exact: true }).fill('确认文字');
  await popup.getByRole('button', { name: '确认标签', exact: true }).click();
  await expect(body.locator('.label-chip')).toHaveText('确认文字');
  await expect(body.locator('.label-chip')).toHaveAttribute('data-color', 'purple');
  await page.keyboard.press('ControlOrMeta+s');
  await expect(page.locator('.save-state')).toContainText('已保存到服务器');
  await page.reload();
  await expect(body.locator('.label-chip')).toHaveText('确认文字');
  await expect(body.locator('.label-chip')).toHaveAttribute('data-color', 'purple');
});
