import { expect, test } from "./fixtures";
import { testEmail, testPassword } from "./credentials";

test("top title is editable without duplication and saves with body, including narrow and readonly views", async ({ page }) => {
  await page.goto("/login");
  await page.getByLabel("邮箱", { exact: true }).fill(testEmail()); await page.getByLabel("密码", { exact: true }).fill(testPassword());
  await page.getByRole("button", { name: "登录", exact: true }).click();
  const original = "原有标题-" + Date.now();
  await page.locator('.import-button input[type="file"]').setInputFiles({ name: "title.md", mimeType: "text/markdown", buffer: Buffer.from(`# ${original}\n\n原有正文`) });
  const title = page.getByRole("textbox", { name: "笔记标题", exact: true });
  const body = page.locator(".prose-editor");
  await expect(title).toHaveValue(original);
  await expect(body).not.toContainText(original);
  await expect(body).toContainText("原有正文");
  const folderBox = (await page.getByRole("combobox", { name: "移动到文件夹" }).boundingBox())!;
  for (const button of [page.getByTitle("置顶", { exact: true }), page.getByTitle("星标", { exact: true }), page.getByRole("button", { name: "版本历史", exact: true }), page.getByRole("button", { name: "笔记更多", exact: true })]) {
    const box = (await button.boundingBox())!;
    const icon = (await button.locator("svg").boundingBox())!;
    expect(box.height).toBe(folderBox.height);
    expect(Math.abs(icon.y + icon.height / 2 - folderBox.y - folderBox.height / 2)).toBeLessThan(1);
    expect(Math.abs(icon.x + icon.width / 2 - box.x - box.width / 2)).toBeLessThan(1);
  }
  await page.getByRole("button", { name: "版本历史", exact: true }).click();
  await expect(page.locator(".version-panel")).toBeVisible();
  await page.getByRole("button", { name: "关闭版本历史" }).click();
  await body.click();
  await page.keyboard.press("Meta+ArrowDown");
  await page.keyboard.press("Enter");
  await page.getByRole("button", { name: "表格", exact: true }).click();
  await page.getByRole("button", { name: "2 行 2 列", exact: true }).click();
  await expect(body.locator("table")).toHaveCount(1);
  await title.fill("更新后的标题");
  await title.press("Enter");
  await expect(body).toBeFocused();
  await page.keyboard.insertText("正文追加");
  await expect(page.locator(".save-state")).toHaveText("已保存到服务器");
  const titleBox = (await title.boundingBox())!;
  const statusBox = (await page.locator(".save-state").boundingBox())!;
  expect(statusBox.x).toBeGreaterThanOrEqual(titleBox.x + titleBox.width);
  expect(Math.abs(statusBox.y + statusBox.height / 2 - titleBox.y - titleBox.height / 2)).toBeLessThan(2);
  await page.reload();
  await expect(title).toHaveValue("更新后的标题");
  await expect(body).not.toContainText("更新后的标题");
  await expect(body).toContainText("正文追加");
  await expect(body).toContainText("原有正文");
  await expect(body.locator("table")).toHaveCount(1);
  await page.getByRole("button", { name: "切换到只读模式", exact: true }).click();
  await expect(title).toHaveAttribute("readonly", "");
  await page.getByRole("button", { name: "切换到编辑模式", exact: true }).click();
  await title.fill("切换前的标题");
  const previous = page.url();
  await page.getByRole("button", { name: "新建笔记", exact: true }).click();
  await expect(page).not.toHaveURL(previous);
  await expect(title).toHaveValue("");
  await page.goto(previous);
  await expect(title).toHaveValue("切换前的标题");
  await page.setViewportSize({ width: 320, height: 740 });
  await title.fill("窄屏长标题".repeat(20));
  await expect(title).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await title.fill("");
  await expect(page.locator(".save-state")).toHaveText("已保存到服务器");
  const narrowTitle = (await title.boundingBox())!;
  const narrowStatus = (await page.locator(".save-state").boundingBox())!;
  expect(narrowStatus.x).toBeGreaterThanOrEqual(narrowTitle.x + narrowTitle.width);
  expect(Math.abs(narrowStatus.y + narrowStatus.height / 2 - narrowTitle.y - narrowTitle.height / 2)).toBeLessThan(2);
  await page.reload();
  await expect(title).toHaveValue("");
  await expect(body).toContainText("正文追加");
  await expect(body).toContainText("原有正文");
});
