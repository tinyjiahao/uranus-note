import { test, expect } from './fixtures';
import { testEmail, testPassword } from './credentials';
test.use({ trace: 'off' });
test('home starts empty and switching scopes clears the editor', async ({ page }) => {
  await page.goto('/login');
  await page.getByLabel('邮箱', { exact: true }).fill(testEmail());
  await page.getByLabel('密码', { exact: true }).fill(testPassword());
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.locator('.workspace')).toBeVisible();
  await expect(page.locator('.note-row')).toHaveCount(0);
  await expect(page.locator('.editor-panel')).toBeEmpty();
  await expect(page.locator('.scope-button.active')).toHaveCount(0);
  await page.getByRole('button', { name: '全部笔记', exact: true }).click();
  await expect(page.locator('.note-row').first()).toBeVisible();
  await page.locator('.note-row').first().click();
  await expect(page.locator('.prose-editor')).toBeVisible();
  const noteURL = page.url();
  await page.getByRole('button', { name: '已加星标', exact: true }).click();
  await expect(page.locator('.editor-panel')).toBeEmpty();
  await expect(page).toHaveURL(/\/$/);
  await page.reload();
  await expect(page.locator('.workspace')).toBeVisible();
  await expect(page.locator('.scope-button.active')).toHaveCount(0);
  await expect(page.locator('.note-row')).toHaveCount(0);
  await expect(page.locator('.editor-panel')).toBeEmpty();
  await page.goto(noteURL);
  await expect(page.locator('.prose-editor')).toBeVisible();
  await expect(page.locator('.folder-row .scope-button.active')).toHaveCount(1);
  await page.locator('.folder-row .scope-button').first().click();
  await expect(page.locator('.editor-panel')).toBeEmpty();
});
